package org.example.fiveletters.solving.common.domain;

public enum Letter {
    A        ('а', 0b00000000000000000000000000000001),
    B        ('б', 0b00000000000000000000000000000010),
    V        ('в', 0b00000000000000000000000000000100),
    G        ('г', 0b00000000000000000000000000001000),
    D        ('д', 0b00000000000000000000000000010000),
    E        ('е', 0b00000000000000000000000000100000),
    ZH       ('ж', 0b00000000000000000000000001000000),
    Z        ('з', 0b00000000000000000000000010000000),
    I        ('и', 0b00000000000000000000000100000000),
    Y        ('й', 0b00000000000000000000001000000000),
    K        ('к', 0b00000000000000000000010000000000),
    L        ('л', 0b00000000000000000000100000000000),
    M        ('м', 0b00000000000000000001000000000000),
    N        ('н', 0b00000000000000000010000000000000),
    O        ('о', 0b00000000000000000100000000000000),
    P        ('п', 0b00000000000000001000000000000000),
    R        ('р', 0b00000000000000010000000000000000),
    S        ('с', 0b00000000000000100000000000000000),
    T        ('т', 0b00000000000001000000000000000000),
    U        ('у', 0b00000000000010000000000000000000),
    F        ('ф', 0b00000000000100000000000000000000),
    H        ('х', 0b00000000001000000000000000000000),
    TS       ('ц', 0b00000000010000000000000000000000),
    CH       ('ч', 0b00000000100000000000000000000000),
    SH       ('ш', 0b00000001000000000000000000000000),
    SHCH     ('щ', 0b00000010000000000000000000000000),
    HARD_SIGN('ъ', 0b00000100000000000000000000000000),
    YY       ('ы', 0b00001000000000000000000000000000),
    SOFT_SIGN('ь', 0b00010000000000000000000000000000),
    YE       ('э', 0b00100000000000000000000000000000),
    YU       ('ю', 0b01000000000000000000000000000000),
    YA       ('я', 0b10000000000000000000000000000000);
    
    public final char value;
    public final int mask;
    
    Letter(char value, int mask) {
        this.value = value;
        this.mask = mask;
    }

    @Override
    public String toString() {
        return String.valueOf(value);
    }
}
